def detect(text):
    """Код NLLB для языка текста или None, если определить не удалось."""
    sample = text[:1000]
    letters = [ch for ch in sample if ch.isalpha()]
    if not letters:
        return None
    total = len(letters)
    kana = sum(_KANA[0] <= ord(ch) <= _KANA[1] for ch in letters)
    if kana * 5 > total:
        return "jpn_Jpan"
    for lo, hi, code in _SCRIPTS:
        if sum(lo <= ord(ch) <= hi for ch in letters) * 2 > total:
            return code
    try:
        from langdetect import DetectorFactory, detect_langs
        DetectorFactory.seed = 0  # одинаковый результат для одного и того же текста
        best = detect_langs(sample)[0].lang
    except Exception:  # noqa: BLE001 — короткий или «пустой» текст
        return None
    return _LANGDETECT.get(best)
